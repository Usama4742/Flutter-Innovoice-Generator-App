import 'dart:convert';
import 'package:flutter/material.dart';
import 'package:innvoice_generator/provider/invoice_provider.dart';
import 'package:innvoice_generator/widgets/theme.dart';
import 'package:mobile_scanner/mobile_scanner.dart';
import 'package:provider/provider.dart';
import 'invoice_details.dart';

class ScanInvoiceScreen extends StatefulWidget {
  const ScanInvoiceScreen({super.key});

  @override
  State<ScanInvoiceScreen> createState() => _ScanInvoiceScreenState();
}

class _ScanInvoiceScreenState extends State<ScanInvoiceScreen> {
  final MobileScannerController scannerController =
      MobileScannerController();

  bool isProcessing = false;

  @override
  void dispose() {
    scannerController.dispose();
    super.dispose();
  }

  // ============================================================
  // QR DETECTED
  // ============================================================

  Future<void> _onDetect(BarcodeCapture capture) async {
    if (isProcessing) return;

    if (capture.barcodes.isEmpty) return;

    final barcode = capture.barcodes.first;

    final rawValue = barcode.rawValue;

    if (rawValue == null || rawValue.trim().isEmpty) {
      return;
    }

    setState(() {
      isProcessing = true;
    });

    await scannerController.stop();

    try {
      final invoiceNumber = _extractInvoiceNumber(rawValue);

      if (invoiceNumber == null || invoiceNumber.isEmpty) {
        throw Exception('Invalid invoice QR code.');
      }

      if (!mounted) return;

      final provider = context.read<InvoiceProvider>();

      final invoice = await provider.findByInvoiceNumber(
        invoiceNumber,
      );

      if (!mounted) return;

      if (invoice == null) {
        await _showNotFound(invoiceNumber);
        return;
      }

      Navigator.pushReplacement(
        context,
        MaterialPageRoute(
          builder: (_) => InvoiceDetailsScreen(
            invoiceId: invoice.id!,
          ),
        ),
      );
    } catch (e) {
      if (!mounted) return;

      await _showError(
        'Invalid invoice QR code.',
      );
    }
  }

  // ============================================================
  // EXTRACT INVOICE NUMBER
  // ============================================================

  String? _extractInvoiceNumber(String rawValue) {
    final value = rawValue.trim();

    // QR generated by our invoice PDF.
    try {
      final decoded = jsonDecode(value);

      if (decoded is Map<String, dynamic>) {
        final type = decoded['type']?.toString();

        final invoiceNumber =
            decoded['invoiceNumber']?.toString();

        if (type == 'invoice' &&
            invoiceNumber != null &&
            invoiceNumber.isNotEmpty) {
          return invoiceNumber;
        }
      }
    } catch (_) {
      // Not JSON.
    }

    // Fallback:
    // If a QR contains only the invoice number.
    if (value.startsWith('INV-')) {
      return value;
    }

    return null;
  }

  // ============================================================
  // NOT FOUND
  // ============================================================

  Future<void> _showNotFound(String invoiceNumber) async {
    if (!mounted) return;

    await showDialog(
      context: context,
      builder: (dialogContext) {
        return AlertDialog(
          title: const Text(
            'Invoice Not Found',
            style: TextStyle(
              fontWeight: FontWeight.w800,
            ),
          ),
          content: Text(
            'No saved invoice was found for '
            '$invoiceNumber.',
          ),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.pop(dialogContext);
              },
              child: Text(
                'Scan Again',
                style: TextStyle(
                  color: AppTheme.primaryBlue,
                  fontWeight: FontWeight.w700,
                ),
              ),
            ),
          ],
        );
      },
    );

    if (!mounted) return;

    setState(() {
      isProcessing = false;
    });

    await scannerController.start();
  }

  // ============================================================
  // ERROR
  // ============================================================

  Future<void> _showError(String message) async {
    if (!mounted) return;

    await showDialog(
      context: context,
      builder: (dialogContext) {
        return AlertDialog(
          title: const Text(
            'Scan Error',
            style: TextStyle(
              fontWeight: FontWeight.w800,
            ),
          ),
          content: Text(message),
          actions: [
            TextButton(
              onPressed: () {
                Navigator.pop(dialogContext);
              },
              child: Text(
                'Try Again',
                style: TextStyle(
                  color: AppTheme.primaryBlue,
                  fontWeight: FontWeight.w700,
                ),
              ),
            ),
          ],
        );
      },
    );

    if (!mounted) return;

    setState(() {
      isProcessing = false;
    });

    await scannerController.start();
  }

  // ============================================================
  // BUILD
  // ============================================================

  @override
  Widget build(BuildContext context) {
    final primaryColor = AppTheme.primaryBlue;

    return Scaffold(
      appBar: AppBar(
        title: const Text(
          'Scan Invoice',
          style: TextStyle(
            fontWeight: FontWeight.w800,
          ),
        ),
        actions: [
          IconButton(
            onPressed: () {
              scannerController.toggleTorch();
            },
            icon: const Icon(
              Icons.flash_on_rounded,
            ),
          ),
        ],
      ),

      body: Stack(
        children: [
          MobileScanner(
            controller: scannerController,
            onDetect: _onDetect,
          ),

          Center(
            child: Container(
              width: 270,
              height: 270,
              decoration: BoxDecoration(
                border: Border.all(
                  color: Colors.white,
                  width: 3,
                ),
                borderRadius: BorderRadius.circular(22),
              ),
            ),
          ),

          Positioned(
            left: 30,
            right: 30,
            bottom: 50,
            child: Container(
              padding: const EdgeInsets.symmetric(
                horizontal: 20,
                vertical: 16,
              ),
              decoration: BoxDecoration(
                color: Colors.black.withOpacity(0.70),
                borderRadius: BorderRadius.circular(16),
              ),
              child: Column(
                children: [
                  const Text(
                    'Scan Invoice QR Code',
                    textAlign: TextAlign.center,
                    style: TextStyle(
                      color: Colors.white,
                      fontSize: 17,
                      fontWeight: FontWeight.w800,
                    ),
                  ),

                  const SizedBox(height: 6),

                  Text(
                    isProcessing
                        ? 'Loading invoice...'
                        : 'Place the QR code inside the frame.',
                    textAlign: TextAlign.center,
                    style: const TextStyle(
                      color: Colors.white70,
                      fontSize: 13,
                    ),
                  ),

                  if (isProcessing) ...[
                    const SizedBox(height: 12),

                    SizedBox(
                      width: 22,
                      height: 22,
                      child: CircularProgressIndicator(
                        strokeWidth: 2.5,
                        color: primaryColor,
                      ),
                    ),
                  ],
                ],
              ),
            ),
          ),
        ],
      ),
    );
  }
}
